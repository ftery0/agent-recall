package adapters

import (
	"github.com/ftery0/agent-recall/internal/memory"
	"testing"
)

func TestAttributionHook(t *testing.T) {
	pre := func(command string) memory.Object {
		return memory.Object{"hook_event_name": "PreToolUse", "tool_input": map[string]any{"command": command}}
	}
	denied := []string{
		"git commit -m \"$(cat <<'EOF'\nfix: 수정\n\nCo-authored-by: Codex <noreply@openai.com>\nEOF\n)\"",
		"git commit -m 'fix: 수정' -m 'Co-Authored-By: Claude Opus <noreply@anthropic.com>'",
		"gh pr create --title 수정 --body 'Generated with [Codex](https://openai.com/codex/).'",
	}
	for _, command := range denied {
		if AttributionHook(pre(command)) == nil {
			t.Errorf("막아야 함: %q", command)
		}
	}
	allowed := []string{
		"git commit -m 'fix: generated by copilot 설정 오류 수정'",
		"git commit -m 'fix: 수정' -m 'Co-authored-by: 김철수 <kim@example.com>'",
		"grep -rn 'Co-authored-by: Codex' .",
		"git log --grep 'Co-authored-by: Claude'",
	}
	for _, command := range allowed {
		if AttributionHook(pre(command)) != nil {
			t.Errorf("막으면 안 됨: %q", command)
		}
	}
	post := pre(denied[0])
	post["hook_event_name"] = "PostToolUse"
	if AttributionHook(post) != nil {
		t.Error("PreToolUse 에서만 막아야 함")
	}
}
